// The golden vectors of the validation (section 3.5): the client predicts
// its own movement with the same formula as validateMove, written again in
// TypeScript, and the one thing that keeps the two from drifting apart is
// this file, which both test suites read. Go is the reference: the file is
// made from validateMove and committed.
//
// After a change to the validation or to DefaultConfig:
//
//	go test ./internal/ghosttag -run TestValidateVectors -update
//
// and commit the file with the change; the TypeScript test then says
// whether the client still agrees.
var updateVectors = flag.Bool("update", false, "rewrite testdata/validate_vectors.json from validateMove")

const vectorsPath = "testdata/validate_vectors.json"

// vectorTolerance is how far a number in the file may be from what the
// code computes. JSON numbers round-trip float64 exactly, so anything above
// zero is a change, not noise; the tolerance only lets a reader of the file
// in another language compare the same way.
const vectorTolerance = 1e-9

type vectorXY struct {
	X float64 `json:"x"`
	Y float64 `json:"y"`
}

type vectorPrev struct {
	X     float64 `json:"x"`
	Y     float64 `json:"y"`
	Theta float64 `json:"theta"`
	Slack float64 `json:"slack"`
}

// vectorIn is one validation step. prev is the player's last validated
// motion, measured dt_ms before raw arrived; the arena has radius r.
type vectorIn struct {
	Prev vectorPrev `json:"prev"`
	Raw  vectorXY   `json:"raw"`
	DtMs float64    `json:"dt_ms"`
	Role string     `json:"role"`
	R    float64    `json:"r"`
}

type vectorOut struct {
	Pos     vectorXY `json:"pos"`
	Theta   float64  `json:"theta"`
	Slack   float64  `json:"slack"`
	Clamped bool     `json:"clamped"`
}

type vectorCase struct {
	Name string    `json:"name"`
	In   vectorIn  `json:"in"`
	Out  vectorOut `json:"out"`
}

type vectorFile struct {
	About string       `json:"about"`
	Cfg   clientConfig `json:"cfg"`
	Cases []vectorCase `json:"cases"`
}

const vectorsAbout = "Golden vectors of the Ghost Tag movement validation (docs/ghosttag-design-v3.1.md, sections 1.2 and 3.5). " +
	"Each case is one step of a player who has a previous validated packet (has_prev_motion true): " +
	"from prev, dt_ms later, the player in role asks to be at raw in an arena of radius r. " +
	"cfg holds the constants, in the shape of snap.cfg. Generated by the Go test " +
	"(go test ./internal/ghosttag -run TestValidateVectors -update); do not edit by hand."

// vectorInputs are the cases, inputs only; their outputs are computed. At
// 40 ms the runner's budget is 260 * 0.04 = 10.4 units and its turn limit
// 4.2 * 0.04 = 0.168 rad; the hunter's budget is 225 * 0.04 = 9 units.
func vectorInputs() []vectorCase {
	const runner, hunter = "RUNNER", "HUNTER"
	at := func(x, y, theta, slack float64) vectorPrev { return vectorPrev{x, y, theta, slack} }
	origin := func(slack float64) vectorPrev { return at(0, 0, 0, slack) }
	pt := func(x, y float64) vectorXY { return vectorXY{x, y} }
	pol := func(r, theta float64) vectorXY { return vectorXY{r * math.Cos(theta), r * math.Sin(theta)} }
	c := func(name string, prev vectorPrev, raw vectorXY, dtMs float64, role string, r float64) vectorCase {
		return vectorCase{Name: name, In: vectorIn{Prev: prev, Raw: raw, DtMs: dtMs, Role: role, R: r}}
	}
	return []vectorCase{
		// Straight lines: the budget, and nothing else.
		c("runner_straight_full_speed_no_slack", origin(0), pt(100, 0), 40, runner, 500),
		c("runner_straight_full_speed_full_slack", origin(25), pt(100, 0), 40, runner, 500),
		c("runner_straight_under_budget_saves_slack", origin(0), pt(6, 0), 40, runner, 500),
		c("runner_straight_exactly_the_budget", origin(0), pt(10.4, 0), 40, runner, 500),
		c("hunter_straight_full_speed_no_slack", origin(0), pt(100, 0), 40, hunter, 500),
		c("hunter_straight_under_budget_saves_slack", origin(0), pt(4, 0), 40, hunter, 500),

		// The runner's turn limit omega_max * dt, and the turn speed penalty.
		c("runner_turn_below_limit", origin(0), pol(5, 0.1), 40, runner, 500),
		c("runner_turn_at_limit", origin(0), pol(5, 0.168), 40, runner, 500),
		c("runner_turn_above_limit_left_is_clipped", origin(0), pol(5, 0.5), 40, runner, 500),
		c("runner_turn_above_limit_right_is_clipped", origin(0), pol(5, -0.5), 40, runner, 500),
		c("runner_half_turn_request_ties_to_the_left", origin(0), pt(-5, 0), 40, runner, 500),
		c("runner_turn_across_pi_wraps", at(10, 10, 3.0, 0), vectorXY{10 + 5*math.Cos(-3.0), 10 + 5*math.Sin(-3.0)}, 40, runner, 500),
		c("runner_turn_penalty_clipped_turn_full_speed", origin(0), pol(100, 0.5), 40, runner, 500),
		c("runner_turn_penalty_unclipped_turn_full_speed", origin(0), pol(100, 0.1), 40, runner, 500),
		c("runner_turn_penalty_with_slack", origin(25), pol(100, 0.1), 40, runner, 500),
		c("runner_turn_limit_at_17ms", origin(0), pol(5, 0.2), 17, runner, 500),

		// The hunter turns freely and pays no penalty.
		c("hunter_sharp_turn_right_angle_no_limit", origin(0), pol(100, math.Pi/2), 40, hunter, 500),
		c("hunter_reverse_no_limit", origin(0), pt(-100, 0), 40, hunter, 500),
		c("hunter_sharp_turn_no_speed_penalty", origin(0), pol(5, 2.5), 40, hunter, 500),

		// The slack budget: spent, exhausted, refilled, capped.
		c("runner_spends_slack", origin(25), pt(20, 0), 40, runner, 500),
		c("runner_exhausts_slack", origin(10), pt(50, 0), 40, runner, 500),
		c("runner_refills_slack", origin(10), pt(3, 0), 40, runner, 500),
		c("runner_refill_capped_at_slack_max", origin(20), pt(1, 0), 40, runner, 500),
		c("hunter_spends_slack", origin(25), pt(20, 0), 40, hunter, 500),
		c("hunter_standing_still_refills_slack", at(30, -40, 1.2, 0), pt(30, -40), 40, hunter, 500),
		c("runner_standing_still_full_slack_stays_full", at(30, -40, 1.2, 25), pt(30, -40), 40, runner, 500),

		// Displacements around move_eps (0.001): below it nothing turns.
		c("runner_micro_move_below_eps_keeps_theta", at(10, 10, 1.0, 5), pt(10.0006, 9.9995), 40, runner, 500),
		c("hunter_micro_move_below_eps_keeps_theta", at(-10, 10, -2.0, 5), pt(-10.0007, 10.0007), 40, hunter, 500),
		c("hunter_move_just_above_eps_turns", at(0, 0, 0, 0), pt(0, 0.0011), 40, hunter, 500),
		c("runner_move_just_above_eps_turn_clipped", at(0, 0, 0, 0), pt(0, 0.0011), 40, runner, 500),

		// The arena: a position outside it is scaled onto the circle.
		c("outside_arena_at_r0", at(495, 0, 0, 25), pt(510, 0), 40, runner, 500),
		c("outside_arena_at_r_min", at(275, 0, 0, 25), pt(290, 0), 40, runner, 280),
		c("outside_arena_between_r0_and_r_min", at(385, 0, 0, 25), pt(400, 0), 40, runner, 390),
		c("outside_arena_diagonal_hunter", at(240, 240, math.Pi/4, 25), pt(260, 260), 40, hunter, 350),
		c("inside_arena_at_r_min_untouched", at(250, 0, 0, 25), pt(260, 0), 40, runner, 280),
		c("standing_still_outside_shrunk_arena", at(300, 0, 0, 5), pt(300, 0), 40, runner, 280),
		c("micro_move_outside_shrunk_arena", at(0, 300, math.Pi/2, 5), pt(0, 300.0005), 40, hunter, 290),

		// dt: 0 for a packet bunched with the previous one, the nominal
		// 40, and above dt_max (capped).
		c("dt_0_clustered_runner_straight_spends_slack", origin(25), pt(5, 0), 0, runner, 500),
		c("dt_0_clustered_runner_cannot_turn", origin(25), pol(5, 0.3), 0, runner, 500),
		c("dt_0_clustered_no_slack_cannot_move", origin(0), pt(5, 0), 0, runner, 500),
		c("dt_0_clustered_hunter_turns_freely", origin(25), pol(5, 2.0), 0, hunter, 500),
		c("dt_0_standing_still_no_refill", at(30, -40, 1.2, 5), pt(30, -40), 0, runner, 500),
		c("dt_100_runner_turn_limit", origin(0), pol(100, 0.3), 100, runner, 500),
		c("dt_at_max_250", origin(0), pt(200, 0), 250, runner, 500),
		c("dt_above_max_1000_capped", origin(0), pt(200, 0), 1000, runner, 500),
		c("dt_above_max_2000_turn_limit_capped", origin(0), pol(100, 1.5), 2000, runner, 500),
		c("dt_above_max_5000_hunter_capped", origin(0), pt(100, 0), 5000, hunter, 500),
		c("runner_negative_quadrant", at(-120.5, -45.25, -2.5, 12.5), pt(-130, -50), 37, runner, 500),
	}
}

// runVector is one case through validateMove.
func runVector(t *testing.T, c *Config, in vectorIn) vectorOut {
	t.Helper()
	r := map[string]role{"RUNNER": roleRunner, "HUNTER": roleHunter}[in.Role]
	require.NotEqual(t, roleNone, r, "role %q", in.Role)
	m := motion{pos: vec{in.Prev.X, in.Prev.Y}, theta: in.Prev.Theta, ts: t0, hasPrev: true, slack: in.Prev.Slack}
	now := t0.Add(time.Duration(in.DtMs * float64(time.Millisecond)))
	next, clamped, err := validateMove(c, m, r, vec{in.Raw.X, in.Raw.Y}, now, in.R)
	require.NoError(t, err)
	return vectorOut{Pos: vectorXY{next.pos.X, next.pos.Y}, Theta: next.theta, Slack: next.slack, Clamped: clamped}
}

// generateVectors is the file as the code makes it now.
func generateVectors(t *testing.T) vectorFile {
	t.Helper()
	c := DefaultConfig()
	f := vectorFile{About: vectorsAbout, Cfg: clientConfigOf(&c), Cases: vectorInputs()}
	for i := range f.Cases {
		f.Cases[i].Out = runVector(t, &c, f.Cases[i].In)
	}
	return f
}

// TestValidateVectors: the committed file is what validateMove produces
// from its inputs with DefaultConfig, number for number. With -update it
// rewrites the file instead.
func TestValidateVectors(t *testing.T) {
	want := generateVectors(t)
	if *updateVectors {
		b, err := json.MarshalIndent(want, "", "  ")
		require.NoError(t, err)
		require.NoError(t, os.MkdirAll(filepath.Dir(vectorsPath), 0o755))
		require.NoError(t, os.WriteFile(vectorsPath, append(b, '\n'), 0o600))
		t.Logf("wrote %d cases to %s", len(want.Cases), vectorsPath)
		return
	}

	raw, err := os.ReadFile(vectorsPath)
	require.NoError(t, err, "run the test with -update to create it")
	var got vectorFile
	require.NoError(t, json.Unmarshal(raw, &got))

	near := func(what string, w, g float64) {
		t.Helper()
		assert.InDelta(t, w, g, vectorTolerance, "%s: the code gives %v, the file has %v", what, w, g)
	}
	cfgMap := func(c clientConfig) map[string]float64 {
		b, err := json.Marshal(c)
		require.NoError(t, err)
		var m map[string]float64
		require.NoError(t, json.Unmarshal(b, &m))
		return m
	}
	wc, gc := cfgMap(want.Cfg), cfgMap(got.Cfg)
	require.Len(t, gc, len(wc), "cfg fields")
	for k, w := range wc {
		near("cfg."+k, w, gc[k])
	}

	require.Len(t, got.Cases, len(want.Cases), "number of cases; run with -update")
	for i, w := range want.Cases {
		g := got.Cases[i]
		require.Equal(t, w.Name, g.Name, "case %d", i)
		n := w.Name + "."
		near(n+"in.prev.x", w.In.Prev.X, g.In.Prev.X)
		near(n+"in.prev.y", w.In.Prev.Y, g.In.Prev.Y)
		near(n+"in.prev.theta", w.In.Prev.Theta, g.In.Prev.Theta)
		near(n+"in.prev.slack", w.In.Prev.Slack, g.In.Prev.Slack)
		near(n+"in.raw.x", w.In.Raw.X, g.In.Raw.X)
		near(n+"in.raw.y", w.In.Raw.Y, g.In.Raw.Y)
		near(n+"in.dt_ms", w.In.DtMs, g.In.DtMs)
		assert.Equal(t, w.In.Role, g.In.Role, n+"in.role")
		near(n+"in.r", w.In.R, g.In.R)
		near(n+"out.pos.x", w.Out.Pos.X, g.Out.Pos.X)
		near(n+"out.pos.y", w.Out.Pos.Y, g.Out.Pos.Y)
		near(n+"out.theta", w.Out.Theta, g.Out.Theta)
		near(n+"out.slack", w.Out.Slack, g.Out.Slack)
		assert.Equal(t, w.Out.Clamped, g.Out.Clamped, n+"out.clamped")
	}
}

// TestValidateVectorNamesAreUnique: a name says what its case exercises,
// so two cases cannot share one.
func TestValidateVectorNamesAreUnique(t *testing.T) {
	seen := map[string]bool{}
	for _, c := range vectorInputs() {
		assert.False(t, seen[c.Name], "%s twice", c.Name)
		seen[c.Name] = true
	}
}
